export type ProjectCategory =
  | "Education"
  | "Medical"
  | "Government"
  | "Sierra Leone"
  | "Business"
  | "AI"
  | "Creator"
  | "Startup"
  | "Advanced"
  | "Experimental";

export interface Project {
  slug: string;
  title: string;
  category: ProjectCategory;
  tagline: string;
  preview: string; // background gradient or image url
  accent: string; // hex
  problem: string;
  solution: string;
  stack: string[];
  features: string[];
  metrics: { label: string; value: string }[];
  demo: string; // url or empty
  docs?: string;
}

const grad = (a: string, b: string) =>
  `linear-gradient(135deg, ${a} 0%, ${b} 100%)`;

function make(
  slug: string,
  title: string,
  category: ProjectCategory,
  tagline: string,
  accent: string,
  accent2: string,
  problem: string,
  solution: string,
  stack: string[],
  features: string[],
  metrics: [string, string][],
): Project {
  return {
    slug,
    title,
    category,
    tagline,
    preview: grad(accent, accent2),
    accent,
    problem,
    solution,
    stack,
    features,
    metrics: metrics.map(([label, value]) => ({ label, value })),
    demo: "",
  };
}

